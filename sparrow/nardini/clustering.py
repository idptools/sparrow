def compare_gin_references(reference, other=None, clip=GIN_CLIP):
    """Match one set of centroids onto another, one-to-one.

    Answers "did my clustering recover the published grammars?". Cluster numbering
    is arbitrary, so a useful comparison has to pair centroids up rather than
    compare labels: this solves the optimal one-to-one assignment that minimizes
    total centroid distance (the Hungarian algorithm).

    Parameters
    ----------
    reference : GINReference
        Your clusters, typically from :func:`build_gin_reference`.
    other : GINReference, optional
        What to compare against. Defaults to the bundled published human GIN
        reference.
    clip : float, optional
        Unused in the distance itself - both sets of centroids already live in
        clipped space - but recorded in the summary for provenance. Default 3.0.

    Returns
    -------
    dict
        ``'pairs'`` is a list of dicts, one per cluster of ``reference``, each with
        ``'cluster'``, ``'description'``, ``'matched_cluster'``,
        ``'matched_description'``, ``'distance'`` and ``'num_idrs'``.
        ``'mean_distance'`` and ``'median_distance'`` summarize the match.

        Two yardsticks make those numbers interpretable, and you need both.
        ``'separation_scale'`` is the typical spacing between the *other*
        reference's own centroids: a mean match distance well below it means the
        two clusterings largely agree, and comparable or above means they do not.
        ``'reference_separation_scale'`` is the same quantity for *your* centroids,
        and guards against a trap - if your clustering found no real structure its
        centroids all sit near the origin, which makes them close to everything and
        produces a flatteringly small match distance. If your separation scale is
        far below the other's, your clusters are not comparable structure however
        well they appear to match.

        All distances are **squared** Euclidean, matching
        :func:`~sparrow.nardini.gin.assign_gin_clusters` and
        :attr:`~sparrow.nardini.gin.GINReference.separation_scale`.

    Raises
    ------
    sparrow.sparrow_exceptions.SparrowException
        If the two references have different feature spaces or different backends,
        or if either has more clusters than the other can pair with.

    Examples
    --------
    >>> report = compare_gin_references(mine)                    # doctest: +SKIP
    >>> report["mean_distance"], report["separation_scale"]      # doctest: +SKIP
    (12.4, 17.8)
    """
    from scipy.optimize import linear_sum_assignment

    from sparrow.nardini.gin import load_gin_reference

    if other is None:
        other = load_gin_reference()

    if tuple(reference.feature_names) != tuple(other.feature_names):
        raise SparrowException(
            "Cannot compare references with different feature spaces "
            f"({len(reference.feature_names)} vs {len(other.feature_names)} "
            "features, or a different feature order)."
        )
    if reference.backend != other.backend:
        raise SparrowException(
            f"Cannot compare centroids in '{reference.backend}' space against "
            f"'{other.backend}' space - the statistics are on different scales."
        )

    # Squared Euclidean, matching assign_gin_clusters and
    # GINReference.separation_scale. Mixing squared and unsquared here would make
    # the reported distances silently incomparable to separation_scale, which is
    # the only yardstick that makes them interpretable.
    difference = reference.centroids[:, None, :] - other.centroids[None, :, :]
    distances = np.sum(difference**2, axis=2)

    rows, columns = linear_sum_assignment(distances)

    pairs = []
    for row, column in zip(rows, columns):
        pairs.append(
            {
                "cluster": int(reference.clusters[row]),
                "description": reference.describe(int(reference.clusters[row])),
                "matched_cluster": int(other.clusters[column]),
                "matched_description": other.describe(int(other.clusters[column])),
                "distance": float(distances[row, column]),
                "num_idrs": int(
                    reference.num_idrs.get(int(reference.clusters[row]), 0)
                ),
            }
        )

    matched = np.array([pair["distance"] for pair in pairs])
    return {
        "pairs": pairs,
        "mean_distance": float(np.mean(matched)),
        "median_distance": float(np.median(matched)),
        "max_distance": float(np.max(matched)),
        "separation_scale": float(other.separation_scale),
        "reference_separation_scale": float(reference.separation_scale),
        "num_pairs": len(pairs),
        "unmatched": int(max(len(reference), len(other)) - len(pairs)),
        "clip": None if clip is None else float(abs(clip)),
    }
