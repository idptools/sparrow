def _kmeans(vectors, k, seed, n_init, max_iter):
    """Run k-means with restarts, returning the lowest-inertia solution.

    Uses ``scipy.cluster.vq.kmeans2`` with k-means++ initialization, so no new
    dependency. Empty clusters are treated as a failed restart rather than
    silently tolerated, because an empty cluster means k is too large for the data
    and a centroid would otherwise be left at its initialization.
    """
    from scipy.cluster.vq import kmeans2

    best = None
    failures = 0

    for attempt in range(n_init):
        # a distinct, deterministic seed per restart
        restart_seed = None if seed is None else int(seed) + attempt
        try:
            # k-means++ divides by the total squared distance when picking each
            # seed point, which is zero once the remaining points are duplicates.
            # That restart is degenerate and gets discarded below, so scipy's
            # RuntimeWarning about it is an internal detail the caller cannot act
            # on - the actionable message is the ClusteringQualityWarning.
            with warnings.catch_warnings():
                warnings.simplefilter("ignore", RuntimeWarning)
                centroids, labels = kmeans2(
                    vectors,
                    k,
                    minit="++",
                    iter=max_iter,
                    seed=restart_seed,
                    missing="raise",
                )
        except Exception:
            failures += 1
            continue

        if not np.all(np.isfinite(centroids)):
            # a degenerate init can leave a centroid at NaN
            failures += 1
            continue

        inertia = float(np.sum((vectors - centroids[labels]) ** 2))
        if best is None or inertia < best[2]:
            best = (centroids, labels, inertia)

    if best is None:
        raise SparrowException(
            f"k-means could not fit {k} non-empty clusters to "
            f"{vectors.shape[0]} vectors in {n_init} attempts. Use a smaller k, or "
            "more sequences."
        )

    return (*best, failures)


def build_gin_reference(
    result,
    k=DEFAULT_NUM_CLUSTERS,
    clip=GIN_CLIP,
    seed=None,
    n_init=DEFAULT_NUM_INIT,
    max_iter=300,
    descriptions=None,
    feature_names=None,
    backend=None,
):
    """Cluster a set of NARDINI+ vectors into your own GIN-style reference.

    Follows the published procedure: clip the z-scores, then k-means. The result
    is a :class:`~sparrow.nardini.gin.GINReference` that
    :func:`~sparrow.nardini.gin.assign_gin_clusters` accepts in place of the
    bundled human one.

    Parameters
    ----------
    result : NardiniResult or array_like
        The vectors to cluster. A :class:`~sparrow.nardini.vectors.NardiniResult`
        is preferred, since it carries the feature names and the backend. A raw
        ``(n_sequences, n_features)`` array also works, in which case
        ``feature_names`` and ``backend`` should be given.
    k : int, optional
        Number of clusters. Default 30, matching the published analysis. There is
        nothing magic about 30 for your own data.
    clip : float or None, optional
        Clip z-scores to ``[-clip, +clip]`` before clustering, so a few extreme
        features cannot dominate the distances. Default 3.0, matching the
        published analysis. Must match the ``clip`` used at assignment time.
    seed : int or None, optional
        Seed for the k-means initialization. Pass one: without it the centroids
        are not reproducible, and cluster numbering is arbitrary either way.
    n_init : int, optional
        Number of restarts; the lowest-inertia solution wins. Default 10.
    max_iter : int, optional
        Iteration limit per restart. Default 300.
    descriptions : dict, optional
        Hand-authored ``{cluster: description}`` labels. Any cluster you omit gets
        one derived from its centroid by :func:`describe_centroid`.
    feature_names : sequence of str, optional
        Required if ``result`` is a bare array.
    backend : str, optional
        Which patterning statistic produced the vectors. Taken from ``result``
        when available; required for a bare array if it was not ``'nardini'``.

    Returns
    -------
    sparrow.nardini.gin.GINReference
        Centroids, per-cluster sizes, derived descriptions, and metadata
        recording k, clip, seed, inertia and the backend.

    Raises
    ------
    sparrow.sparrow_exceptions.SparrowException
        If ``k`` is not sensible for the number of vectors, if feature names are
        missing for a bare array, or if k-means cannot fit non-empty clusters.

    Notes
    -----
    Cluster numbers carry no meaning across runs. To relate your clusters to the
    published grammars, use :func:`compare_gin_references`.

    Examples
    --------
    >>> reference = build_gin_reference(vectors, k=30, seed=0)   # doctest: +SKIP
    >>> reference.describe(0)                                    # doctest: +SKIP
    'blocky neg-neg, high Frac E, D patches'
    """
    if hasattr(result, "zscores"):
        vectors = np.atleast_2d(np.asarray(result.zscores, dtype=np.float64))
        names = list(feature_names or result.feature_names)
        resolved_backend = backend or getattr(result, "backend", DEFAULT_BACKEND)
        num_sequences = len(getattr(result, "names", vectors))
    else:
        vectors = np.atleast_2d(np.asarray(result, dtype=np.float64))
        if feature_names is None:
            raise SparrowException(
                "build_gin_reference needs feature_names when given a bare array. "
                "Pass a NardiniResult instead, or feature_names=... explicitly."
            )
        names = list(feature_names)
        resolved_backend = backend or DEFAULT_BACKEND
        num_sequences = vectors.shape[0]

    if vectors.shape[1] != len(names):
        raise SparrowException(
            f"Got {vectors.shape[1]} features but {len(names)} feature names."
        )

    k = int(k)
    if k < 2:
        raise SparrowException(f"k must be at least 2, got {k}")
    if k > vectors.shape[0]:
        raise SparrowException(
            f"Cannot fit {k} clusters to {vectors.shape[0]} sequences. Use a "
            "smaller k, or cluster more sequences."
        )
    if not np.all(np.isfinite(vectors)):
        raise SparrowException(
            "The vectors contain non-finite values, which k-means cannot handle."
        )

    # clip exactly as assignment does, so centroids and queries share a space
    clustered = vectors if clip is None else np.clip(vectors, -abs(clip), abs(clip))

    per_cluster = vectors.shape[0] / k
    if per_cluster < MIN_SEQUENCES_PER_CLUSTER:
        warnings.warn(
            f"Clustering {vectors.shape[0]} sequences into {k} clusters leaves only "
            f"{per_cluster:.1f} per cluster on average (recommended: at least "
            f"{MIN_SEQUENCES_PER_CLUSTER}). k-means will return {k} centroids "
            "regardless of whether the data supports that many, and they will "
            "happily assign every query sequence to one of them. Use a smaller k, "
            "or more sequences. Compare reference_separation_scale against "
            "separation_scale in compare_gin_references() to see whether your "
            "centroids describe structure on a comparable scale.",
            ClusteringQualityWarning,
            stacklevel=2,
        )

    centroids, labels, inertia, failures = _kmeans(clustered, k, seed, n_init, max_iter)

    # order clusters largest-first, so cluster 0 is the most populated grammar.
    # k-means numbering is arbitrary; this at least makes it stable and useful.
    sizes = np.bincount(labels, minlength=k)
    order = np.argsort(-sizes)
    centroids = centroids[order]
    sizes = sizes[order]

    resolved_descriptions = {}
    for cluster in range(k):
        given = (descriptions or {}).get(cluster)
        resolved_descriptions[cluster] = given or describe_centroid(
            centroids[cluster], names
        )

    metadata = {
        "derived_from": "build_gin_reference",
        "backend": resolved_backend,
        "k": k,
        "clip": None if clip is None else float(abs(clip)),
        "seed": None if seed is None else int(seed),
        "n_init": int(n_init),
        "failed_restarts": int(failures),
        "num_sequences": int(num_sequences),
        "inertia": float(inertia),
        "note": (
            "Derived clusters, not the published GIN reference. Descriptions are "
            "generated from centroid extremes unless supplied. Cluster numbers are "
            "ordered by size and are not comparable to published cluster numbers."
        ),
    }

    return GINReference(
        feature_names=names,
        clusters=np.arange(k),
        centroids=centroids,
        descriptions=resolved_descriptions,
        num_idrs={cluster: int(sizes[cluster]) for cluster in range(k)},
        metadata=metadata,
        backend=resolved_backend,
    )


