def describe_centroid(centroid, feature_names, n=DEFAULT_DESCRIPTION_FEATURES):
    """Summarize one centroid as a short human-readable phrase.

    Reads the centroid's most extreme features and renders them in the language
    that fits each kind: patterning features describe *arrangement* (blocky versus
    well-mixed), compositional ones describe *content* (high versus low).

    Parameters
    ----------
    centroid : array_like
        1D centroid coordinates.
    feature_names : sequence of str
        Names matching ``centroid``.
    n : int, optional
        How many features to mention. Default 3.

    Returns
    -------
    str
        For example ``'blocky neg-neg, high Frac E, D patches'``, or
        ``'no distinctive features'`` if nothing reaches the threshold.

    Examples
    --------
    >>> describe_centroid([2.5, -1.9], ["neg-neg", "Frac K"])   # doctest: +SKIP
    'blocky neg-neg, low Frac K'
    """
    centroid = np.asarray(centroid, dtype=np.float64)
    names = list(feature_names)

    if centroid.ndim != 1 or centroid.size != len(names):
        raise SparrowException(
            f"describe_centroid needs a 1D centroid matching {len(names)} feature "
            f"names, got shape {centroid.shape}"
        )

    phrases = []
    for index in np.argsort(-np.abs(centroid)):
        value = centroid[index]
        if abs(value) < _DESCRIPTION_MIN_Z or len(phrases) >= n:
            break

        name = names[index]
        if "-" in name:
            # a patterning feature: this is about arrangement
            phrases.append(f"{'blocky' if value > 0 else 'well-mixed'} {name}")
        elif name.endswith(" Patch"):
            # "Q Patch" reads better as "Q patches" / "few Q patches"
            residue = name[: -len(" Patch")]
            phrases.append(
                f"{residue} patches" if value > 0 else f"few {residue} patches"
            )
        else:
            phrases.append(f"{'high' if value > 0 else 'low'} {name}")

    return ", ".join(phrases) if phrases else "no distinctive features"


